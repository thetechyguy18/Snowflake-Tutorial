-- 2nd on Notification Integration for Azure Event Grid

-- Task 3:
-- Create or replace a notification integration AZURE_PIPE_EVENT of type QUEUE targeting an Azure Storage Queue
CREATE OR REPLACE NOTIFICATION INTEGRATION AZURE_PIPE_EVENT
    ENABLED = TRUE
    TYPE = QUEUE
    NOTIFICATION_PROVIDER = AZURE_STORAGE_QUEUE
    AZURE_STORAGE_QUEUE_PRIMARY_URI = 'https://snowflake1808.queue.core.windows.net/snowpipequeue'
    AZURE_TENANT_ID = 'b5516084-f1d0-49ae-baa0-1d1b1dffcb0c';

-- Task 4:
-- Describe AZURE_PIPE_EVENT to retrieve AZURE_CONSENT_URL and AZURE_MULTI_TENANT_APP_NAME for granting Cloud IAM permissions
DESC NOTIFICATION INTEGRATION AZURE_PIPE_EVENT;

-- 3rd on Target Ingestion Table and Pipe Creation

-- Task 5:
-- Create or replace a target pipeline table ORDERS_STREAM_PIPELINE with ORDER_DATE (DATE), REGION (STRING), ITEM (STRING), and ORDER_QTY (INT)
CREATE OR REPLACE TABLE ASSIGNMENT_DB.STAGING.ORDERS_STREAM_PIPELINE (
    ORDER_DATE DATE,
    REGION STRING,
    ITEM STRING,
    ORDER_QTY INT
);

-- Task 6:
-- Create or replace an auto-ingest Snowpipe PIPE_ORDERS_AUTOINGEST configured with AUTO_INGEST = TRUE, linking AZURE_PIPE_EVENT to load data into ORDERS_STREAM_PIPELINE
CREATE OR REPLACE PIPE ASSIGNMENT_DB.STAGING.PIPE_ORDERS_AUTOINGEST
    AUTO_INGEST = TRUE
    INTEGRATION = AZURE_PIPE_EVENT
AS
    COPY INTO ASSIGNMENT_DB.STAGING.ORDERS_STREAM_PIPELINE
    FROM @ASSIGNMENT_DB.STAGING.AZURE_ORDERS_STAGE
    FILE_FORMAT = ASSIGNMENT_DB.STAGING.CSV_FF
    ON_ERROR = 'CONTINUE';

-- Task 7:
-- Check the status, definition, and execution metadata of all pipes in ASSIGNMENT_DB.STAGING
SHOW PIPES IN SCHEMA ASSIGNMENT_DB.STAGING;

