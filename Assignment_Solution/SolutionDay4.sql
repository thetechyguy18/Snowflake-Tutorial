--> Phase-2: Unnesting Arrays using LATERAL FLATTEN

-- 1st on Inspecting Array Elements

-- Task 1:
-- Query the raw ITEMS array directly from RAW_LOGS and observe how the array structure displays
SELECT PAYLOAD:items 
FROM ASSIGNMENT_DB.STAGING.RAW_LOGS;

-- 2nd on Exploding Arrays into Relational Rows

-- Task 2:
-- Use LATERAL FLATTEN on PAYLOAD:ITEMS to explode the array into individual records alongside top-level event and user attributes
SELECT 
    PAYLOAD:event_id::INT AS EVENT_ID,
    PAYLOAD:user.id::STRING AS USER_ID,
    PAYLOAD:user.region::STRING AS USER_REGION,
    F.VALUE:sku::STRING AS ITEM_SKU,
    F.VALUE:price::INT AS ITEM_PRICE
FROM ASSIGNMENT_DB.STAGING.RAW_LOGS,
LATERAL FLATTEN(INPUT => PAYLOAD:items) F;

-- Task 3:
-- Inspect all default pseudo-columns generated by FLATTEN (INDEX, KEY, VALUE, LEVEL, THIS) using f.*
SELECT 
    F.*
FROM ASSIGNMENT_DB.STAGING.RAW_LOGS,
LATERAL FLATTEN(INPUT => PAYLOAD:items) F;

-- Task 4:
-- Write an unnested query extracting EVENT_ID, item ordinal position (INDEX), item SKU, and item PRICE
SELECT 
    PAYLOAD:event_id::INT AS EVENT_ID,
    F.INDEX AS ITEM_NUMBER,
    F.VALUE:sku::STRING AS ITEM_SKU,
    F.VALUE:price::INT AS ITEM_PRICE
FROM ASSIGNMENT_DB.STAGING.RAW_LOGS,
LATERAL FLATTEN(INPUT => PAYLOAD:items) F;

