ON SCHEMA ASSIGNMENT_DB.STAGING 
TO ROLE ANALYTICS_READER_ROLE;

-- Task 5:
-- Grant SELECT privilege on ALL existing tables in ASSIGNMENT_DB.STAGING to ANALYTICS_READER_ROLE
