-- Grant USAGE privilege on ASSIGNMENT_DB to ANALYTICS_READER_ROLE
GRANT USAGE 
ON DATABASE ASSIGNMENT_DB 
TO ROLE ANALYTICS_READER_ROLE;

-- Task 4:
-- Grant USAGE privilege on schema ASSIGNMENT_DB.STAGING to ANALYTICS_READER_ROLE
